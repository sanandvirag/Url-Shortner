import { prisma } from "../lib/prisma.js";
import generateShortCode from "../utils/base62.js";

interface CreateUrlData {
    originalUrl: string;
    expiresAt?: string | null;
    userId?: string;
    customAlias?: string | null;
}

const MAX_CREATE_ATTEMPTS = 5;

const isUniqueConstraintError = (error: unknown): boolean => (
    typeof error === "object" &&
    error !== null &&
    "code" in error &&
    (error as { code?: unknown }).code === "P2002"
); //It checks whether the error generated by Prisma is a unique constraint violation. Prisma return code P2002 for unique constrint voilation.

const isCustomAliasConstraintError = (error: unknown): boolean => {
    if (typeof error !== "object" || error === null || !("meta" in error)) {
        return false;
    }

    const target = (error as { meta?: { target?: unknown } }).meta?.target;
    return Array.isArray(target) && target.includes("customAlias");
}; //This determines whether a Prisma uniqueness error specifically happened because of: custom alias

export const createShortUrl = async ({originalUrl, expiresAt, userId, customAlias,}: CreateUrlData) => {

    if (customAlias) {
        const aliasConflict = await prisma.url.findFirst({
            where: {
                OR: [
                    { customAlias },
                    { shortCode: customAlias },
                ],
            },
        });

        if (aliasConflict) {
            throw new Error("Custom alias already exists");
        }
    }

    for (let attempt = 1; attempt <= MAX_CREATE_ATTEMPTS; attempt += 1) {
        const shortCode = generateShortCode();

        try {
            return await prisma.url.create({
                data: {
                    originalUrl,
                    shortCode,
                    customAlias: customAlias ?? null,
                    expiresAt: expiresAt ? new Date(expiresAt) : null,
                    userId: userId ?? null,
                },
            });
        } catch (error) {
            if (!isUniqueConstraintError(error)) {
                throw error;
            }

            if (isCustomAliasConstraintError(error)) {
                throw new Error("Custom alias already exists");
            }

            if (attempt === MAX_CREATE_ATTEMPTS) {
                throw new Error("Could not generate a unique short code");
            }
        }
    }

    throw new Error("Could not generate a unique short code");
}; //

export const updateUrlExpiry = async (
    urlId: string,
    userId: string,
    expiresAt: string | null
) => {
    // First verify that this URL belongs to the logged-in user
    const url = await prisma.url.findFirst({
        where: {
            id: urlId,
            userId: userId,
        },
    });

    if (!url) {
        throw new Error("URL not found or unauthorized");
    }

    const updatedUrl = await prisma.url.update({
        where: {
            id: urlId,
        },
        data: {
            expiresAt: expiresAt === null ? null : new Date(expiresAt),
        },
    });

    return updatedUrl;
};

export const deleteShortUrl = async (urlId: string, userId: string) => {
    const result = await prisma.url.deleteMany({
        where: {
            id: urlId,
            userId,
        },
    });

    if (result.count === 0) {
        throw new Error("URL not found or unauthorized");
    }
};

interface AnalyticsOptions {
    limit?: number;
    offset?: number;
}

export const getUserAnalytics = async (
    userId: string,
    { limit = 100, offset = 0 }: AnalyticsOptions = {}
) => {
    const urlWhere = { userId };
    const [urls, totalUrls, totalClicks, activeUrls] = await Promise.all([
        prisma.url.findMany({
            where: urlWhere,
            orderBy: {
                createdAt: "desc",
            },
            skip: offset,
            take: limit,
            include: {
                _count: {
                    select: {
                        clicks: true,
                    },
                },
            },
        }),
        prisma.url.count({ where: urlWhere }),
        prisma.click.count({ where: { url: urlWhere } }),
        prisma.url.count({
            where: {
                ...urlWhere,
                OR: [
                    { expiresAt: null },
                    { expiresAt: { gt: new Date() } },
                ],
            },
        }),
    ]);

    const analytics = urls.map((url) => ({
        id: url.id,
        shortCode: url.shortCode,
        customAlias: url.customAlias,
        originalUrl: url.originalUrl,
        expiresAt: url.expiresAt,
        totalClicks: url._count.clicks,
        clicks: [],
    }));

    return {
        totalClicks,
        urls: analytics,
        pagination: {
            limit,
            offset,
            totalUrls,
            activeUrls,
            hasMore: offset + urls.length < totalUrls,
        },
    };
};